//! Construction tokens and origin labels that keep synthetic data explicit.
//!
//! Synthetic telemetry must never enter the production acquisition path. Nothing in this crate can be
//! constructed "by accident": [`crate::SyntheticTelemetryProvider::new`] requires a [`SyntheticMode`],
//! which can only be obtained from an explicit [`DemoMode::acknowledge`] or [`TestMode::acknowledge`]
//! call, so every use is visible (and greppable) at the call site. Every tick the provider produces is
//! labelled with [`DataOrigin::Synthetic`], and every identity string in its frames and scoring starts with
//! [`SYNTHETIC_NAME_PREFIX`] so a UI shows "SYNTHETIC DATA" even after the frame went through the recorder
//! or the network.

/// Text a UI shows for synthetic data.
pub const SYNTHETIC_LABEL: &str = "SYNTHETIC DATA";

/// Prefix of every identity string (vehicle, track, team names) the provider produces.
pub const SYNTHETIC_NAME_PREFIX: &str = "[SYNTHETIC] ";

/// True if `name` carries the synthetic identity prefix.
pub fn is_synthetic_name(name: &str) -> bool {
    name.starts_with(SYNTHETIC_NAME_PREFIX)
}

/// Prefixes `name` with [`SYNTHETIC_NAME_PREFIX`] (idempotent).
pub fn synthetic_name(name: &str) -> String {
    if is_synthetic_name(name) {
        name.to_owned()
    } else {
        format!("{SYNTHETIC_NAME_PREFIX}{name}")
    }
}

/// Token for the user-visible demo mode. The UI must display [`SYNTHETIC_LABEL`] while it is active.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct DemoMode {
    _private: (),
}

impl DemoMode {
    /// The caller acknowledges that the data shown is synthetic and will be labelled as such.
    pub const fn acknowledge() -> Self {
        Self { _private: () }
    }
}

/// Token for automated tests and development tools.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct TestMode {
    _private: (),
}

impl TestMode {
    /// The caller acknowledges that the data is synthetic and only used for tests or development.
    pub const fn acknowledge() -> Self {
        Self { _private: () }
    }
}

/// Why synthetic data is generated. Only constructible from a [`DemoMode`] or [`TestMode`] token.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum SyntheticMode {
    /// Demo mode (user visible, labelled).
    Demo(DemoMode),
    /// Tests / development.
    Test(TestMode),
}

impl SyntheticMode {
    /// The purpose without the token.
    pub const fn purpose(self) -> SyntheticPurpose {
        match self {
            SyntheticMode::Demo(_) => SyntheticPurpose::Demo,
            SyntheticMode::Test(_) => SyntheticPurpose::Test,
        }
    }
}

impl From<DemoMode> for SyntheticMode {
    fn from(token: DemoMode) -> Self {
        SyntheticMode::Demo(token)
    }
}

impl From<TestMode> for SyntheticMode {
    fn from(token: TestMode) -> Self {
        SyntheticMode::Test(token)
    }
}

/// Purpose of a synthetic stream.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum SyntheticPurpose {
    Demo,
    Test,
}

/// Where a tick's data comes from. The provider only ever produces [`DataOrigin::Synthetic`]; the type
/// exists so consumers can carry the label next to frames (e.g. in a demo pipeline).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum DataOrigin {
    /// Generated by this crate.
    Synthetic(SyntheticPurpose),
}

impl DataOrigin {
    /// Always true for this crate's data.
    pub const fn is_synthetic(self) -> bool {
        matches!(self, DataOrigin::Synthetic(_))
    }

    /// UI label for this origin.
    pub const fn label(self) -> &'static str {
        match self {
            DataOrigin::Synthetic(_) => SYNTHETIC_LABEL,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_are_prefixed_once() {
        let n = synthetic_name("Hypercar H1");
        assert!(is_synthetic_name(&n));
        assert_eq!(synthetic_name(&n), n);
        assert!(!is_synthetic_name("Hypercar H1"));
    }

    #[test]
    fn tokens_map_to_purpose() {
        assert_eq!(
            SyntheticMode::from(DemoMode::acknowledge()).purpose(),
            SyntheticPurpose::Demo
        );
        assert_eq!(
            SyntheticMode::from(TestMode::acknowledge()).purpose(),
            SyntheticPurpose::Test
        );
        assert!(DataOrigin::Synthetic(SyntheticPurpose::Test).is_synthetic());
        assert_eq!(
            DataOrigin::Synthetic(SyntheticPurpose::Demo).label(),
            SYNTHETIC_LABEL
        );
    }
}
